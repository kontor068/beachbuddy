import { LanguageCode } from '../types';
import { getLocalizedCopy, type LocalizedCopy } from './i18n';
import { waveSteepness, SEA_REFERENCE_PERIOD_S } from './waveCharacter';
import type { CalmnessTone } from './suitabilityTone';

/**
 * ΤΟ ΚΥΜΑ ΠΟΥ ΕΙΝΑΙ ΧΑΜΗΛΟ ΚΑΙ ΠΑΡ' ΟΛΑ ΑΥΤΑ ΕΝΟΧΛΕΙ.
 *
 * ΤΙ ΤΟ ΓΕΝΝΗΣΕ. Αναφορά επισκέπτη «Είχε κύμα», Σκάλα Κεφαλονιάς (3105), 15/08/2026, 3 Μποφόρ ΒΑ.
 * Η γεωμετρία ήταν σωστή (τομέας NE: onshore +0,423, fetch 20 χλμ, `exposed`) και ο αριθμός ήταν
 * σωστός: 0,68 μ. Αλλά στα **3,3 δευτερόλεπτα**, δηλαδή αποτομότητα Hs/L0 = 0,040 — νερό που
 * σπάει συνέχεια. Η οθόνη δεν είπε τίποτα γι' αυτό, με δύο ανεξάρτητους τρόπους:
 *
 *   1. Το χρώμα σώπασε ΟΡΙΑΚΑ: `seaStateSeverityM` έβγαλε 0,79 μ. έναντι `SEA_STATE_AMBER_M`
 *      = 0,80. Ένα εκατοστό.
 *   2. Και η λέξη σώπασε ΔΟΜΙΚΑ: το `isShortPeriodSea` (`utils/waveCharacter.ts:101`) υπάρχει από
 *      τις 28/07/2026 με σχόλιο «Used only to choose wording» — και **δεν το καλούσε κανείς**.
 *      Μηδέν καταναλωτές σε ολόκληρο το repo. Ο άξονας του χαρακτήρα κύματος μπήκε μισός: ο
 *      αριθμός μετρούσε την αποτομότητα, η γλώσσα δεν την ανέφερε ποτέ.
 *
 * ΓΙΑΤΙ ΛΕΞΗ ΚΑΙ ΟΧΙ ΚΑΤΩΦΛΙ. Το προφανές θα ήταν να κατέβει το 0,80 ή να ανέβει το
 * `CHOP_EXPONENT`. Μετρήθηκε (`scripts/measureChopExponent.mjs`, 930 παραλίες σε 14 περιοχές,
 * ζωντανά, 15/08): εκθέτης 1,5 σκουραίνει 23 παραλίες και ξυπνάει 8 από πλήρη σιωπή, **χωρίς
 * καμία ψεύτικη ηρεμία** — δηλαδή είναι ασφαλές. Δεν μπήκε παρ' όλα αυτά, γιατί **δεν υπάρχει
 * μέτρηση που να λέει ποιος εκθέτης είναι ο σωστός**, το ίδιο το `waveCharacter.ts:36-37`
 * προειδοποιεί ότι οι σταθερές απορροφούν τον ορισμό περιόδου του παρόχου, και η βίβλος
 * (PORISMA §Γ4) έχει ήδη ορίσει ότι μια μετρημένη-αλλά-μη-επιβεβαιωμένη ρύθμιση είναι απόφαση του
 * Μίλτου, όχι του κώδικα. Η λέξη προσθέτει πληροφορία χωρίς να μετακινήσει κανένα όριο ασφαλείας.
 *
 * ΓΙΑΤΙ ΔΕΝ ΓΙΝΕΤΑΙ ΜΟΝΙΜΗ ΤΑΜΠΕΛΑ. Σκέτη «κοντή περίοδος» θα μιλούσε στο **43,6%** των παραλιών
 * — ταμπέλα, ρητά απαγορευμένη. Με τις τρεις πύλες παρακάτω πέφτει στο **6,9%** (64/930), και
 * αυτό μετρήθηκε, δεν εκτιμήθηκε.
 *
 * ΤΙ ΔΕΝ ΛΕΕΙ ΠΟΤΕ: μέτρα. Ο αριθμός είναι ήδη στην οθόνη από πάνω· μια δεύτερη αναφορά ύψους
 * εδώ θα ήταν ο ίδιος αριθμός με άλλα λόγια — ακριβώς το «διπλό ρομποτικό κείμενο» που έχει ήδη
 * κοστίσει μια εκκαθάριση.
 */

/**
 * Κάτω από αυτό το κύμα δεν το νιώθεις όσο απότομο κι αν είναι. 0,2 μ. στα 2,5 δλ είναι τεχνικά
 * πολύ απότομο νερό και πρακτικά ασήμαντο· χωρίς αυτό το πάτωμα η πρόταση θα έβγαινε εκεί.
 */
export const CHOPPY_MIN_WAVE_M = 0.4;

/**
 * Αποτομότητα Hs/L0. Το ίδιο το `utils/waveCharacter` δίνει τη βαθμονόμηση στον πίνακά του:
 * 0,45 μ. @ 2,5 δλ → 0,046 (σπάει συνέχεια) · 0,45 μ. @ 8 δλ → 0,0045 (ήπιο κύλισμα).
 *
 * Το 0,035 δεν είναι στρογγυλοποίηση: στα 0,04 η ίδια η Σκάλα που γέννησε τη λειτουργία βγάζει
 * 0,03999 και θα έμενε ΠΑΛΙ σιωπηλή — ένα κατώφλι που αποκλείει την περίπτωσή του είναι λάθος
 * κατώφλι. Μετρημένα μερίδια (930 παραλίες, 15/08): ≥0,03 → 8,7% · **≥0,035 → 6,9%** ·
 * ≥0,04 → 5,4% · ≥0,05 → 0,6%.
 */
export const CHOPPY_MIN_STEEPNESS = 0.035;

/** Χρώματα που λένε «ήρεμα». Πάνω από αυτά η οθόνη ήδη προειδοποιεί και η πρόταση περισσεύει. */
const CALM_TONES: readonly CalmnessTone[] = ['blue', 'yellow'];

/**
 * Μία πρόταση, όχι οικογένεια παραλλαγών ανά ένταση. Ο λόγος είναι καταγεγραμμένος: N
 * σχεδόν-ίδιες γραμμές διαβάζονται σαν μηχανή και δεν προσθέτουν γνώση. Ή υπάρχει κάτι να πεις,
 * ή σιωπή.
 */
/**
 * ⚠️ ΚΑΜΙΑ ΛΕΞΗ ΓΙΑ ΤΟ ΜΕΓΕΘΟΣ. Η πρώτη διατύπωση έλεγε «χαμηλό, αλλά σε χτυπάει συνέχεια» και
 * ήταν λάθος στο ίδιο της το εύρος: οι πύλες παρακάτω επιτρέπουν και κύμα 0,9 μ. πάνω σε κίτρινο
 * χρώμα, όπου το «χαμηλό» είναι ψέμα. Το ύψος το λέει ήδη ο αριθμός δίπλα· εδώ λέγεται μόνο ο
 * ΧΑΡΑΚΤΗΡΑΣ, που είναι ό,τι λείπει.
 */
const CHOPPY_SENTENCE: LocalizedCopy<string> = {
  gr: 'Το κύμα εδώ είναι κοντό και σπαστό — σε χτυπάει συνέχεια, δεν σε σηκώνει.',
  en: 'The sea here is short and choppy — it keeps hitting you rather than lifting you.',
  de: 'Die See ist hier kurz und kabbelig — sie schlägt ständig gegen dich, statt dich zu heben.',
  fr: "La mer est ici courte et hachée — elle vous frappe sans arrêt au lieu de vous soulever.",
  it: 'Qui il mare è corto e increspato — ti colpisce di continuo invece di sollevarti.',
};

export interface ChoppySeaInput {
  /** Το ΩΜΟ ύψος (m) — το ίδιο που τρέφει το `seaStateSeverityM`, όχι η σοβαρότητα. */
  waveHeightM?: number;
  /** Η περίοδος (s) που ταξιδεύει μαζί του. Χωρίς αυτήν δεν υπάρχει γνώμη. */
  periodS?: number;
  /** Το χρώμα που δείχνει ΗΔΗ η οθόνη — η πρόταση μιλάει μόνο όταν εκείνο λέει «ήρεμα». */
  tone?: CalmnessTone;
  language: LanguageCode;
}

/**
 * Η πρόταση, ή `null` όταν δεν δικαιούμαστε γνώμη — και το `null` είναι η κανονική απάντηση.
 *
 * Καμία πύλη εδώ δεν είναι διακοσμητική:
 *  - χωρίς περίοδο δεν ξεχωρίζεις chop από αποθάλασσα, και το να το μαντέψεις είναι ο τρόπος με
 *    τον οποίο γράφτηκαν παλιότερα ψεύτικες προειδοποιήσεις·
 *  - χωρίς το πάτωμα ύψους μιλάει σε νερό που κανείς δεν προσέχει·
 *  - χωρίς την πύλη χρώματος επαναλαμβάνει αυτό που η κάρτα από πάνω λέει ήδη πιο δυνατά.
 */
export const buildChoppySeaLine = ({ waveHeightM, periodS, tone, language }: ChoppySeaInput): string | null => {
  if (typeof waveHeightM !== 'number' || !Number.isFinite(waveHeightM)) return null;
  if (typeof periodS !== 'number' || !Number.isFinite(periodS) || periodS <= 0) return null;
  if (periodS >= SEA_REFERENCE_PERIOD_S) return null;
  if (waveHeightM < CHOPPY_MIN_WAVE_M) return null;
  if (waveSteepness(waveHeightM, periodS) < CHOPPY_MIN_STEEPNESS) return null;
  if (tone !== undefined && !CALM_TONES.includes(tone)) return null;
  return getLocalizedCopy(language, CHOPPY_SENTENCE);
};
