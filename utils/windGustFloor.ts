/**
 * ΤΟ ΩΡΙΑΙΟ ΜΕΣΟ ΣΤΡΩΝΕΙ ΤΙΣ ΚΟΡΥΦΕΣ — η ριπή τις ξαναφέρνει.
 *
 * ΤΙ ΜΕΤΡΗΘΗΚΕ (18/08/2026, `scripts/auditWindAgainstStations.mjs`). Κριτής: 25 ανεμόμετρα
 * ελληνικών παράκτιων αεροδρομίων (METAR, 10-λεπτος μέσος στα 10 μ. — το ίδιο μέγεθος που δίνει
 * το Open-Meteo), το μοντέλο ζητημένο ΣΤΙΣ ΣΥΝΤΕΤΑΓΜΕΝΕΣ ΤΟΥ ΣΤΑΘΜΟΥ. Τέσσερα παραθυρα,
 * ~32.000 ώρες-σταθμοί:
 *
 *   παράθυρο        μεροληψία   κλίση   λάθος χαμηλά   λάθος ψηλά
 *   20/05-05/06     −1,75       0,641   39,6%          21,7%
 *   20/06-05/07     −2,20       0,673   40,6%          20,6%
 *   10/07-25/07     −2,12       0,694   40,4%          21,6%
 *   04-18/08        −2,30       0,710   40,6%          20,7%
 *
 * Η κλίση της ευθείας «μοντέλο = a + b × μέτρηση» κάθεται σταθερά στο 0,64-0,71. Κλίση <1
 * σημαίνει ΣΥΜΠΙΕΣΗ ΕΥΡΟΥΣ: φουσκώνει την άπνοια (+4,9 χλμ/ώ στα 0 Μπφ), ισοπεδώνει το μελτέμι
 * (−6,8 στα 5 Μπφ, −12,4 στα 7 Μπφ όπου δείχναμε χαμηλότερα στο **97%** των ωρών).
 *
 * ΔΕΝ ΕΙΝΑΙ ΤΟΠΟΓΡΑΦΙΑ ΤΟΥ ΣΤΑΘΜΟΥ. Αν έφταιγε ότι «το αεροδρόμιο είναι πιο ανοιχτό από την
 * παραλία», η μεροληψία θα ήταν σταθερά αρνητική· αντ' αυτού γυρίζει πρόσημο με την ένταση, και
 * σε τέσσερις σταθμούς (Νάξος +5,3, Χίος +3,2, Σκιάθος +2,1, Χανιά +2,1) υπερεκτιμούμε.
 *
 * ΔΕΝ ΛΥΝΕΤΑΙ ΜΕ ΑΛΛΟ ΜΟΝΤΕΛΟ. Η διάμεσος τεσσάρων άλλων μοντέλων έχει ΜΕΓΑΛΥΤΕΡΟ σφάλμα
 * (5,65 έναντι 5,23 χλμ/ώ) και ΧΕΙΡΟΤΕΡΗ συμπίεση (κλίση 0,628), και στα 6-8 Μποφόρ υποεκτιμά
 * ακόμα πιο βαριά (−11,6 / −17,6). Η εγγραφή 31/07 της βίβλου — «το `best_match` επαληθεύτηκε
 * έναντι δορυφόρου στα 0,03 m/s» — ισχύει. Το μοντέλο είναι το καλύτερο διαθέσιμο· απλώς κάθε
 * αριθμητικό μοντέλο στρώνει τις κορυφές.
 *
 * ΓΙΑΤΙ Η ΡΙΠΗ ΚΑΙ ΟΧΙ ΠΟΛΛΑΠΛΑΣΙΑΣΤΗΣ. Δοκιμάστηκε πρώτα «×1,20 πάνω από 4 Μποφόρ»:
 * βαθμονομήθηκε στο παράθυρο του Αυγούστου, φαινόταν δωρεάν εκεί, και **κόπηκε** στα άλλα τρία —
 * χειροτέρευε σφάλμα και ακρίβεια Μποφόρ σε 3 από 4. Ήταν overfit. Η ριπή δεν είναι αυθαίρετος
 * συντελεστής: κουβαλά την πληροφορία «πόσο ασταθής είναι η ροή αυτή την ώρα», που είναι ακριβώς
 * ό,τι χάνει ο ωριαίος μέσος και ακριβώς ό,τι βλέπει μια κάμερα.
 *
 * ΤΙ ΚΕΡΔΙΖΕΙ ΣΕ ΧΛΜ/Ω (σάρωση σε τρία παράθυρα, με ριπή×0,50):
 *
 *                        σήμερα                    με ριπή×0,50
 *   σφάλμα (χλμ/ώ)       4,43 / 4,99 / 5,23        4,29 / 4,89 / 5,27   (αμετάβλητο)
 *   σωστό Μποφόρ         38,6% / 38,0% / 38,7%     43,7% / 41,6% / 41,0%
 *   μεροληψία            −1,75 / −2,12 / −2,30     −0,16 / −0,49 / −0,75
 *   λάθος χαμηλά ≥1 Μπφ  39,6% / 40,4% / 40,6%     28,3% / 30,0% / 32,4%
 *   λάθος ψηλά ≥1 Μπφ    21,7% / 21,6% / 20,7%     28,0% / 28,4% / 26,6%   ← το τίμημα
 *
 * ΚΑΙ ΤΙ ΚΑΝΕΙ ΣΤΟ ΧΡΩΜΑ — το μόνο κριτήριο που βλέπει ο χρήστης. Ίδιος κώδικας
 * (`utils/suitabilityTone`), τρέξιμο τρεις φορές: με τη ΜΕΤΡΗΣΗ, με τον ωμό μέσο, με τον δάπεδο.
 *
 *   συντελεστής   σωστό χρώμα              ψεύτικη ηρεμία          ψεύτικος συναγερμός
 *   σήμερα        78,0 / 72,3 / 68,5%      12,2 / 13,3 / 13,6%     3,4 / 3,9 / 4,2%
 *   0,45          78,1 / 72,2 / 68,0%      10,3 / 11,0 / 11,5%     5,0 / 5,7 / 6,2%
 *   **0,50**      77,6 / 71,4 / 67,6%       9,3 / 10,1 / 10,2%     6,3 / 6,8 / 7,3%
 *   0,55          76,8 / 70,2 / 67,6%       7,6 /  8,5 /  8,2%     8,3 / 8,7 / 8,9%
 *   0,60          74,5 / 67,9 / 66,2%       6,1 /  6,9 /  6,4%    11,2 / 10,8 / 11,3%
 *
 * ΠΡΟΣΟΧΗ — ΔΕΝ ΕΙΝΑΙ ΚΑΘΑΡΗ ΝΙΚΗ, ΕΙΝΑΙ ΑΝΤΑΛΛΑΓΗ. Η συνολική ακρίβεια του χρώματος πέφτει
 * ~0,5 μονάδα. Αυτό που κερδίζεται είναι η ΚΑΤΕΥΘΥΝΣΗ του σφάλματος: η «ψεύτικη ηρεμία» (λέμε
 * «πάμε» ενώ το όργανο λέει όχι) πέφτει κατά ένα τέταρτο, με αντάλλαγμα ισόποσο «ψεύτικο
 * συναγερμό» (λέμε «προσοχή» ενώ ήταν καλά). Οι δύο δεν κοστίζουν το ίδιο: η πρώτη στέλνει
 * κόσμο σε παραλία με αέρα, η δεύτερη απλώς χάνει μία πρόταση από μια λίστα 2.850.
 *
 * Η ένταση (0,50) είναι ΑΠΟΦΑΣΗ ΠΡΟΪΟΝΤΟΣ του Μίλτου, 18/08/2026, με τον παραπάνω πίνακα
 * μπροστά του — όχι βελτιστοποίηση. Το 0,45 και το 0,55 είναι εξίσου υπερασπίσιμα σημεία της
 * ίδιας καμπύλης· αλλάζει ΜΟΝΟ με νέα απόφαση, όχι με νέα μέτρηση.
 *
 * ΜΗΔΕΝ ΕΠΙΠΛΕΟΝ ΚΛΗΣΕΙΣ. Το `wind_gusts_10m` ζητείται ήδη σε κάθε αίτημα
 * (`services/forecast/openMeteoProvider.ts:188,207`) — απλώς δεν το χρησιμοποιούσε κανείς εδώ.
 *
 * ΟΡΙΑ ΤΗΣ ΜΕΤΡΗΣΗΣ, να διαβαστούν πριν αλλάξει ο συντελεστής:
 *   • Ο κριτής είναι αεροδρόμιο, όχι παραλία.
 *   • Τα τέσσερα παράθυρα είναι Μάιος-Αύγουστος. ΧΕΙΜΩΝΑΣ ΔΕΝ ΔΟΚΙΜΑΣΤΗΚΕ (το ιστορικό του
 *     Open-Meteo φτάνει 92 ημέρες πίσω).
 *   • Το 0,55 βγήκε από σάρωση σε τρία παράθυρα, όχι από θεωρία.
 */

/**
 * Κλάσμα της ριπής που λειτουργεί ως δάπεδο για τον ωριαίο μέσο.
 *
 * ΑΥΤΟΣ Ο ΑΡΙΘΜΟΣ ΕΙΝΑΙ ΑΠΟΦΑΣΗ, ΟΧΙ ΕΥΡΗΜΑ. Ο πίνακας χρώματος παραπάνω δείχνει μια συνεχή
 * καμπύλη ανταλλαγής — κάθε σκαλί προς τα πάνω κόβει ψεύτικες ηρεμίες και προσθέτει ψεύτικους
 * συναγερμούς. Δεν υπάρχει «βέλτιστο» χωρίς να πεις πόσο χειρότερο είναι το ένα λάθος από το
 * άλλο. Στο 0,60 ο ψεύτικος συναγερμός τριπλασιάζεται (4% → 11%) και η ακρίβεια πέφτει 3
 * μονάδες· στο 0,40 η μεροληψία μένει −1,5 και μισό πρόβλημα μένει άλυτο.
 */
export const GUST_FLOOR_FACTOR = 0.50;

/**
 * ΤΟ ΘΑΛΑΣΣΙΝΟ ΚΕΛΙ ΕΞΑΙΡΕΙΤΑΙ — και αυτό είναι το μισό της διόρθωσης.
 *
 * Η πρώτη έκδοση εφάρμοζε τον δάπεδο παντού. ΛΑΘΟΣ, και το έπιασαν ΔΥΟ ανεξάρτητοι μάρτυρες:
 *
 *   1. ΔΟΡΥΦΟΡΙΚΟ ΡΑΝΤΑΡ (`reports/wind-model/sheltered-vs-sar.json`, Sentinel-1, ~1 χλμ):
 *      σε ανοιχτό νερό η απόκλιση του μοντέλου είναι **+0,03 m/s** — και στη ζώνη >6 m/s γίνεται
 *      **−0,93**, δηλαδή το μοντέλο ΥΠΕΡεκτιμά εκεί.
 *   2. ΤΑ ΙΔΙΑ ΤΑ ΑΝΕΜΟΜΕΤΡΑ, σπασμένα ανά υψόμετρο του κελιού που απάντησε:
 *
 *      κελί              μεροληψία        κλίση            στα ≥4 Μπφ
 *      θάλασσα (0 μ.)    −0,19 / +0,98    0,963 / 1,104    **+0,44 / +2,68**  ← καμία συμπίεση
 *      ακτή (1-20 μ.)    −1,65 / −1,79    0,656 / 0,679    −6,04 / −5,80
 *      στεριά (>20 μ.)   −3,75 / −4,36    0,736 / 0,731    −6,19 / −6,94
 *
 * Η ΣΥΜΠΙΕΣΗ ΤΩΝ ΚΟΡΥΦΩΝ ΔΕΝ ΥΠΑΡΧΕΙ ΠΑΝΩ ΑΠΟ ΝΕΡΟ (κλίση 0,96-1,10 = τέλεια). Ζει μόνο εκεί
 * που το κελί περιέχει στεριά, γιατί εκεί το μοντέλο εφαρμόζει χερσαία τραχύτητα σε άνεμο που
 * φτάνει από τη θάλασσα. Σε θαλάσσιο κελί ο δάπεδος θα πρόσθετε άνεμο σε ένα νούμερο που ήδη
 * ΥΠΕΡεκτιμά στα δυνατά — ακριβώς το αντίθετο από τον σκοπό του.
 *
 * ΜΕΓΕΘΟΣ: 47,6% των σημείων ανέμου της εφαρμογής (1.265 από 2.872 παραλίες) απαντώνται από
 * υψόμετρο 0. Χωρίς αυτή την εξαίρεση η διόρθωση θα χαλούσε τις μισές παραλίες της χώρας.
 *
 * ΔΙΟΡΘΩΣΗ ΟΝΟΜΑΤΟΣ (18/08/2026, απόγευμα): το `elevation` της απάντησης ΔΕΝ είναι του κελιού,
 * είναι το DEM 90 μ. ΣΤΟ ΣΗΜΕΙΟ που ρωτήθηκε. Αποδείχθηκε με τρεις κλήσεις στο ΙΔΙΟ κελί
 * (37.3125_22.8125, ίδιος άνεμος 7,6 χλμ/ώ): από την πινέζα του Τυρού γυρίζει 0, από το κέντρο
 * του κελιού 242, από άλλο σημείο μέσα του 264.
 *
 * Η ΠΡΟΦΑΝΗΣ ΔΙΟΡΘΩΣΗ ΔΟΚΙΜΑΣΤΗΚΕ ΚΑΙ ΚΟΠΗΚΕ. Αν η πύλη ομαδοποιούσε κατά ΚΕΝΤΡΟ ΚΕΛΙΟΥ, οι
 * κάδοι γίνονται ΧΕΙΡΟΤΕΡΟΙ διαχωριστές (θάλασσα: κλίση 0,751 και μεροληψία −1,52, έναντι
 * 1,104 / +0,98 με το σημείο), και στις ώρες όπου οι δύο ορισμοί διαφωνούν ΥΠΕΡεκτιμούμε κατά
 * +3,12 / +3,52 / +5,34 χλμ/ώ σε τρία παράθυρα. Ο δάπεδος εκεί θα πρόσθετε άνεμο σε νούμερο
 * που ήδη είναι ψηλό. Το `pointElevation` κερδίζει γιατί «η πινέζα κάθεται σε επίπεδο έδαφος
 * στο νερό» προβλέπει την ακρίβεια του μοντέλου καλύτερα από «το κέντρο του κελιού είναι
 * θάλασσα». Η εξαίρεση μένει όπως είναι — μόνο το σχόλιο ήταν λάθος, όχι ο κώδικας.
 */

/**
 * ΠΟΤΕ ΣΠΑΕΙ Η ΕΞΑΙΡΕΣΗ ΤΟΥ ΘΑΛΑΣΣΙΝΟΥ ΣΗΜΕΙΟΥ — ο λόγος ριπής προς μέσο.
 *
 * ΑΦΟΡΜΗ. Τυρός Αρκαδίας 18/08/2026 17:00: μέσος **3,9 χλμ/ώ** με ριπή **22,3** — λόγος 5,7. Η
 * κάρτα έλεγε «1 Μπφ | 0,03 μ.» με ζωντανή κάμερα να δείχνει αέρα και κύμα. Σε πραγματικό άνεμο
 * ο λόγος κάθεται στο 1,3-2,0· πάνω από 3 η ίδια η απάντηση λέει δύο ασύμβατα πράγματα για την
 * ίδια ώρα, και το μεγαλύτερο από τα δύο είναι εκείνο που βλέπει η κάμερα.
 *
 * ΔΕΝ ΕΙΝΑΙ ΤΟ ΙΔΙΟ ΜΕ «Ο ΜΕΣΟΣ ΜΑΣ ΕΙΝΑΙ ΜΙΚΡΟΣ». Ο λόγος μεγαλώνει αυτόματα όταν ο
 * παρονομαστής μικραίνει, οπότε ελέγχθηκε με τον ΔΙΚΟ ΜΑΣ μέσο κρατημένο σταθερό. Ο υψηλός
 * λόγος υποεκτιμά περισσότερο μέσα σε ΚΑΘΕ ζώνη: −4,41 (0-5 χλμ/ώ), −0,53 (5-10), −1,20
 * (10-15), −1,43 (15-20). Η πληροφορία επιβιώνει· δεν είναι artifact.
 *
 * ΤΟ ΚΑΘΕΣΤΩΣ ΕΙΝΑΙ ΔΙΠΛΟ, μέσα στις ώρες που η εξαίρεση αφήνει ακάλυπτες (σημείο ≤0 μ.):
 *
 *   λόγος <2,0   μεροληψία +3,33 / +2,26   κλίση 1,087 / 0,936   ← η εξαίρεση είναι ΣΩΣΤΗ
 *   λόγος ≥3,0   μεροληψία −2,79 / −4,26   κλίση 0,094 / 0,146   ← το μοντέλο πρακτικά τυφλό
 *
 * ΤΟ 3,5 ΕΙΝΑΙ ΤΟ ΜΟΝΟ ΚΑΤΩΦΛΙ ΧΩΡΙΣ ΤΙΜΗΜΑ (`measureGustRatioSeaExemption`, 32.253 ώρες, 4
 * παράθυρα Μάιος-Αύγουστος, κάθε παράθυρο κριτής των άλλων τριών). Στις 199 ώρες που αγγίζει:
 *
 *                        σήμερα      με δάπεδο
 *   σωστό Μποφόρ         18,1%       32,7%
 *   λάθος χαμηλά ≥1 Μπφ  69,3%       45,7%
 *   ψεύτικη ηρεμία        7,2%        6,4%
 *   ψεύτικος συναγερμός   0,0%        0,2%
 *   σωστό χρώμα          92,8%       93,3%
 *   μεροληψία            −4,48       −1,77   ← ΑΚΟΜΑ υποεκτιμά· δεν υπερδιορθώνει
 *
 * Και ανά παράθυρο, ΚΑΝΕΝΑ δεν χαλάει: το «λάθος χαμηλά» πέφτει και στα τέσσερα (71,9→38,6 ·
 * 75,0→51,9 · 72,7→50,0 · 56,5→43,5) και η ψεύτικη ηρεμία δεν ανεβαίνει πουθενά. Στο κατώφλι
 * 3,0 το τίμημα γίνεται σταθερά +0,5-0,8 μονάδες ψεύτικου συναγερμού σε κάθε παράθυρο, χωρίς
 * αντίστοιχο κέρδος στο χρώμα — γι' αυτό 3,5 και όχι 3,0.
 *
 * ΓΙΑΤΙ ΙΔΙΟΣ ΣΥΝΤΕΛΕΣΤΗΣ 0,50 ΚΑΙ ΟΧΙ ΔΕΥΤΕΡΟΣ. Σαρώθηκαν 0,30-0,50 στο ίδιο υποσύνολο· η
 * μεροληψία παραμένει ΑΡΝΗΤΙΚΗ ως το 0,50 (−3,15 στο 0,35, −1,77 στο 0,50), δηλαδή κανένα
 * σκαλί δεν υπερδιορθώνει και το 0,50 είναι απλώς το λιγότερο λάθος. Μια δεύτερη σταθερά θα
 * ήταν ένας ακόμα αριθμός να συντηρείται χωρίς μέτρηση που να τον απαιτεί.
 *
 * ΟΡΙΑ — ΝΑ ΔΙΑΒΑΣΤΟΥΝ ΠΡΙΝ ΤΟ ΚΑΤΩΦΛΙ ΞΑΝΑΓΓΙΧΤΕΙ:
 *   • Οι 199 ώρες προέρχονται από **δύο μόνο σταθμούς** (Νάξος, Κέρκυρα) — τα υπόλοιπα 28
 *     αεροδρόμια δεν κάθονται σε DEM-0 pixel. Το κατώφλι στέκει σε τέσσερα παράθυρα αλλά όχι
 *     σε τέσσερις γεωγραφίες.
 *   • Κανένας σταθμός δεν έχει τη γεωμετρία του Τυρού (στενή λωρίδα κάτω από βουνό 1.000 μ.).
 *     Η αφορμή της διόρθωσης ΔΕΝ είναι μέσα στο δείγμα που την επικύρωσε.
 *   • Μάιος-Αύγουστος μόνο· χειμώνας αδοκίμαστος (το Open-Meteo κρατά 92 ημέρες).
 */
export const INCOHERENT_GUST_RATIO = 3.5;

/**
 * Ο άνεμος που δείχνουμε: ο ωριαίος μέσος, αλλά — ΜΟΝΟ σε κελί με στεριά — ποτέ κάτω από
 * `GUST_FLOOR_FACTOR × ριπή`.
 *
 * Μονάδες αδιάφορες για ταχύτητα/ριπή — ο συντελεστής είναι αδιάστατος, αρκεί τα δύο να είναι
 * στην ΙΔΙΑ μονάδα. Το υψόμετρο είναι πάντα σε ΜΕΤΡΑ και είναι του ΚΕΛΙΟΥ που απάντησε
 * (`elevation` της απάντησης Open-Meteo), όχι της παραλίας.
 *
 * ΧΩΡΙΣ έγκυρη ριπή Ή χωρίς γνωστό υψόμετρο επιστρέφει τον μέσο αμετάβλητο. Και τα δύο κενά
 * κρατούν τη σημερινή συμπεριφορά: μια διόρθωση που δεν ξέρει πού πατάει δεν εφαρμόζεται.
 *
 * ΔΥΟ ΠΟΡΤΕΣ, ΟΧΙ ΜΙΑ. Σε σημείο με στεριά (>0 μ.) ο δάπεδος ισχύει πάντα. Σε σημείο στο 0
 * ισχύει ΜΟΝΟ όταν η ίδια η απάντηση αυτοαναιρείται — ριπή προς μέσο ≥ `INCOHERENT_GUST_RATIO`.
 * Η δεύτερη πόρτα δεν κοιτάει πού είναι η παραλία· κοιτάει αν το μοντέλο λέει δύο ασύμβατα
 * πράγματα για την ίδια ώρα.
 */
export const applyGustFloor = (
  speed: number,
  gust?: number | null,
  pointElevationM?: number | null,
): number => {
  if (!Number.isFinite(speed)) return speed;
  if (typeof gust !== 'number' || !Number.isFinite(gust) || gust <= 0) return speed;
  if (typeof pointElevationM !== 'number' || !Number.isFinite(pointElevationM)) return speed;
  if (pointElevationM <= 0 && !(speed > 0 && gust / speed >= INCOHERENT_GUST_RATIO)) return speed;
  return Math.max(speed, gust * GUST_FLOOR_FACTOR);
};
