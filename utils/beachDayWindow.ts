export const KEY_BEACH_HOURS = {
  /** Πρώτη ώρα (ώρα Ελλάδας, συμπεριλαμβανόμενη) που κρίνει ετυμηγορία, ριπές, βροχή, δυνάμωμα. */
  start: 10,
  /** Τελευταία ώρα (συμπεριλαμβανόμενη). Ήταν 18 ως τις 12/09/2026. */
  end: 20,
  /** Από πότε μετράει το «απόγευμα» για το δυνάμωμα του μελτεμιού. */
  afternoonStart: 13,
  /**
   * Ο ΠΥΡΗΝΑΣ (ως 18) για τους κανόνες που κρίνουν «όλες τις ώρες» ή μέσο όρο — βροχή σε όλες τις κρίσιμες ώρες,
   * μέσος θαλάσσιος βαθμός, εμπιστοσύνη. Αν έπαιρναν και τις 19-20, θα γίνονταν ΗΠΙΟΤΕΡΟΙ (μια βροχερή 10-18 μέρα
   * με στεγνό βράδυ θα έπαυε να είναι «βροχερή» — το έπιασε η πύλη recommendation-scenarios, Milos_RAIN_3BFT).
   * Οι κανόνες ΜΕΓΙΣΤΟΥ (ριπή, χειρότερη ώρα, απογευματινό δυνάμωμα) βλέπουν ως το `end`: μόνο προσθέτουν προσοχή.
   */
  coreEnd: 18,
};

export const isCoreBeachHour = (hour: number): boolean => hour >= KEY_BEACH_HOURS.start && hour <= KEY_BEACH_HOURS.coreEnd;

export const isKeyBeachHour = (hour: number): boolean => hour >= KEY_BEACH_HOURS.start && hour <= KEY_BEACH_HOURS.end;
