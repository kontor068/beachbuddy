/** Ανάλυση του `windShadow`: 24 θέσεις, μία ανά 15°, θέση 0 = 0°. */
export const WIND_SHADOW_SLOTS = 24;
export const WIND_SHADOW_STEP_DEG = 360 / WIND_SHADOW_SLOTS;

/**
 * Πόσο κοντά πρέπει να είναι η στεριά για να λέγεται «ο αέρας ήρθε από πάνω της», σε χιλιόμετρα.
 *
 * ΔΕΝ διαβάζεται εδώ — είναι ψημένο μέσα στο `windShadow` από το geospatial build. Ζει σαν
 * σταθερά ώστε η πύλη (`scripts/validateOffshoreWindNote.mjs`) και το εργαλείο που παράγει το
 * πεδίο να συμφωνούν για το ΤΙ σημαίνει το κάθε '1', και να μην μπορεί να αλλάξει το ένα χωρίς
 * το άλλο. Το 0,30 βγήκε από τη σάρωση: στα 0,5 χλμ η γραμμή έβγαινε σε 7,1% των παραλιών, στα
 * 0,3 σε 3,2%, με τον ίδιο μάρτυρα (11/14 ώρες στη Λυγαριά).
 */
export const WIND_SHADOW_LAND_KM = 0.3;

/**
 * Πόσο φαρδύ παράθυρο γύρω από τη γωνία του ανέμου πρέπει να είναι ΟΛΟ στεριά.
 *
 * Φαρδύτερο = ΑΥΣΤΗΡΟΤΕΡΟ (περισσότερες γωνίες πρέπει να είναι κλειστές). Μετρημένο: ±30° → 6,1%
 * των παραλιών, ±45° → 3,2%, ±60° → 1,4% αλλά χάνει τον μάρτυρα (5/14 ώρες αντί 11/14). Το ±45
 * είναι το πιο σφιχτό που κρατάει ακόμα την παραλία που γέννησε τον κανόνα.
 */
export const OFFSHORE_NOTE_WINDOW_DEG = 45;

/** Κάτω από αυτό κανείς δεν αναρωτιέται γιατί ο αριθμός δείχνει κύμα — και δεν χρειάζεται λόγια. */
export const OFFSHORE_NOTE_MIN_BEAUFORT = 3;

/**
 * Το κύμα κάτω από το οποίο η γραμμή δεν έχει τίποτα να διορθώσει, σε μέτρα.
 *
 * ΔΑΝΕΙΚΟ, όχι βαθμονομημένο: είναι το ίδιο 0,40 που η εφαρμογή ήδη ονομάζει «εδώ σταματάει να
 * είναι επίπεδο νερό» — `FLAT_WATER_SEA_STATE_M` του φίλτρου «Ήρεμο νερό» (§Γ16) και
 * `GLASS_AT_FOUR_MAX_SEA_STATE_M` της πόρτας «απόγειος-γυαλί των 4». Το §Γ16 δανείστηκε το
 * κατώφλι του με τον ίδιο τρόπο και για τον ίδιο λόγο: δύο αριθμοί σε δύο αρχεία που πρέπει να
 * συμφωνούν είναι πώς αρχίζουν δύο επιφάνειες να λένε διαφορετικά πράγματα.
 */
export const OFFSHORE_NOTE_MIN_WAVE_M = 0.4;

/**
 * Και το πάνω όριο: πάνω από αυτό δεν λέμε «πιο ήρεμα» με τίποτα.
 *
 * Είναι η πορτοκαλί γραμμή της εφαρμογής (`SEA_STATE_AMBER_M`). Πάνω από εκεί το ταβάνι θάλασσας
 * έχει ήδη άποψη, και μια καθησυχαστική φράση θα πήγαινε κόντρα σε δικλείδα ασφαλείας.
 * Μετρημένο: μόνο 5 από τις 317 ώρες που ανάβουν κάθονται στο 0,6-0,8 — το όριο δεν κόβει
 * χρήσιμες περιπτώσεις, κόβει την ουρά του ρίσκου.
 */
export const OFFSHORE_NOTE_MAX_WAVE_M = 0.8;

/**
 * Από πόσα Μποφόρ και πάνω η γραμμή κουβαλάει ΚΑΙ την προειδοποίηση, όχι μόνο την ανακούφιση.
 *
 * ⚠️ ΑΥΤΟ ΤΟ ΜΙΣΟ ΔΕΝ ΕΙΝΑΙ ΔΙΑΚΟΣΜΗΤΙΚΟ. Η βίβλος (§Μ2) άφησε ρητή ανοιχτή εκκρεμότητα τη γραμμή
 * «**ο αέρας σε βγάζει στα ανοιχτά**» και τη χαρακτήρισε «πιο επείγουσα, γιατί οι παραλίες που
 * κερδίζουν θέση με απόγειο άνεμο είναι ακριβώς αυτές όπου ένα φουσκωτό φεύγει». Είναι η ΙΔΙΑ
 * συνθήκη που ανάβει αυτή τη γραμμή. Το να τυπώσουμε μόνο το καθησυχαστικό μισό της, ενώ το
 * επικίνδυνο μισό λείπει, θα ήταν μονόπλευρη ανάγνωση της ίδιας μέτρησης.
 *
 * Στα 3 Μποφόρ (12-19 χλμ/ώρα) το «σε βγάζει ανοιχτά» θα ήταν υπερβολή και θα έκανε τη γραμμή να
 * ακούγεται σαν συναγερμό εκεί που δεν είναι· από 4 Μποφόρ (20+ χλμ/ώρα) απόγειος, ένα στρώμα
 * όντως φεύγει.
 */
export const OFFSHORE_NOTE_WARNING_MIN_BEAUFORT = 4;

/** Οι δύο μορφές της γραμμής. Καμία τρίτη — σιωπή δεν είναι μορφή, είναι `null`. */
export type OffshoreWindNoteForm =
  /** 3 Μποφόρ: μόνο «το νερό μπροστά σου είναι πιο ήρεμο απ' ό,τι λέει ο αριθμός». */
  | 'calmer-than-the-number'
  /** 4-5 Μποφόρ: το ίδιο, ΣΥΝ «με στρώμα ή φουσκωτό σε βγάζει ανοιχτά» (§Μ2). */
  | 'calmer-but-pulls-out';

/**
 * Ήρθε ο άνεμος πάνω από στεριά; Όλες οι γωνίες μέσα στο παράθυρο πρέπει να είναι κλειστές.
 *
 * Άγνωστο πεδίο ή άγνωστη γωνία = ΟΧΙ. Κανόνας που μόνο καθησυχάζει δεν επιτρέπεται να ανάβει σε
 * έλλειψη στοιχείων — ο ίδιος κανόνας που έκλεισε την πόρτα της περιόδου σε άγνωστη περίοδο.
 */
export const windArrivedOverLand = (
  windShadow: string | undefined,
  windFromDeg: number | undefined,
  windowDeg: number = OFFSHORE_NOTE_WINDOW_DEG
): boolean => {
  if (typeof windShadow !== 'string' || windShadow.length !== WIND_SHADOW_SLOTS) return false;
  if (typeof windFromDeg !== 'number' || !Number.isFinite(windFromDeg)) return false;

  const centre = Math.round((((windFromDeg % 360) + 360) % 360) / WIND_SHADOW_STEP_DEG);
  const half = Math.round(windowDeg / WIND_SHADOW_STEP_DEG);
  for (let offset = -half; offset <= half; offset += 1) {
    const slot = (centre + offset + WIND_SHADOW_SLOTS) % WIND_SHADOW_SLOTS;
    if (windShadow[slot] !== '1') return false;
  }
  return true;
};

export interface OffshoreWindNoteInput {
  profile?: Pick<GeospatialExposureProfile, 'confidence'> & { windShadow?: string };
  /** Μοίρες από τις οποίες έρχεται ο άνεμος, σε ΑΥΤΗ την παραλία. */
  windFromDeg?: number;
  beaufort?: number;
  /** `shoreDisplayWaveM` — ο αριθμός που τυπώνεται στην οθόνη, όχι κάποιος ενδιάμεσος. */
  displayWaveM?: number;
  /** Η ετυμηγορία της εφαρμογής. `true` σφραγίζει τη γραμμή, σε κάθε άλλη συνθήκη. */
  swimVerdictAvoid?: boolean;
}

/**
 * Τι λέει η γραμμή — ή `null` για σιωπή, που είναι η απάντηση στο 99,2% των ωρών.
 *
 * Η σειρά των ελέγχων είναι από τον φθηνότερο προς τον ακριβότερο ΚΑΙ από τον πιο επικίνδυνο προς
 * τον λιγότερο: η ετυμηγορία «μην κολυμπήσεις» ρωτιέται πρώτη, γιατί είναι η μόνη περίπτωση όπου
 * μια καθησυχαστική φράση θα αντέφασκε ευθέως με δικλείδα ασφαλείας.
 */
export const resolveOffshoreWindNote = ({
  profile,
  windFromDeg,
  beaufort,
  displayWaveM,
  swimVerdictAvoid,
}: OffshoreWindNoteInput): OffshoreWindNoteForm | null => {
  if (swimVerdictAvoid) return null;
  if (profile?.confidence !== 'high') return null;
  if (typeof beaufort !== 'number' || beaufort < OFFSHORE_NOTE_MIN_BEAUFORT) return null;
  if (typeof displayWaveM !== 'number' || !Number.isFinite(displayWaveM)) return null;
  if (displayWaveM < OFFSHORE_NOTE_MIN_WAVE_M || displayWaveM > OFFSHORE_NOTE_MAX_WAVE_M) return null;
  if (!windArrivedOverLand(profile?.windShadow, windFromDeg)) return null;

  return beaufort >= OFFSHORE_NOTE_WARNING_MIN_BEAUFORT
    ? 'calmer-but-pulls-out'
    : 'calmer-than-the-number';
};
