/**
 * Πάνω από τόσο νερό ΣΤΗΝ ΑΚΤΗ, το άθροισμα δικαιούται να αρνηθεί το μπάνιο.
 *
 * ΔΕΝ ΕΙΝΑΙ ΔΙΚΟΣ ΤΟΥ ΑΡΙΘΜΟΣ ΠΙΑ (23/08/2026). Ήταν 0,6 — ένας τρίτος αριθμός για το «πόσο
 * νερό είναι πολύ», ανάμεσα στο 0,8 όπου η θάλασσα αρχίζει να μιλάει στο χρώμα
 * (utils/waveCharacter.SEA_STATE_AMBER_M) και στο 1,2 της μετρημένης πόρτας της ετυμηγορίας.
 * Στο κενό 0,6–0,8 τα δύο συστήματα αντέφασκαν εξ ορισμού: το χρώμα έλεγε «η θάλασσα δεν έχει
 * τίποτα να πει», και το άθροισμα των ποινών επέμενε «μην κολυμπήσεις» — οπότε η πινέζα έπεφτε
 * στο πορτοκαλί ΑΠΟ ΤΗΝ ΕΤΥΜΗΓΟΡΙΑ (cause 'verdict') σε νερό που καμία μέτρησή μας δεν έλεγε
 * άγριο.
 *
 * ΜΕΤΡΗΘΗΚΕ ΖΩΝΤΑΝΑ ΠΡΙΝ ΑΛΛΑΞΕΙ (Λέσβος, 23/08/2026, πρόγνωση για 24/08 10:00): 2 Μπφ στην
 * ακτή, 0,62 μ. @ 3,75 s — 17 πορτοκαλί πινέζες, οι 16 από ετυμηγορία, και η λεζάντα από κάτω
 * μετρούσε «Μέτρια 1». Ο αναγνώστης (ο Μίλτος) δεν μπορούσε να εξηγήσει ούτε το χρώμα ούτε την
 * εξαφάνιση. Με το κατώφλι δεμένο στο 0,8 και οι 16 ξαναγίνονται αυτό που ο άνεμος και η
 * θάλασσα λένε ότι είναι.
 *
 * ΕΝΑ ΚΑΤΩΦΛΙ, ΟΧΙ ΔΥΟ: εισάγεται από το waveCharacter αντί να ξαναγραφτεί, ώστε αν το «πότε
 * μιλάει η θάλασσα» μετακινηθεί ποτέ, να μετακινηθούν ΜΑΖΙ. Η ασφάλεια δεν χαλάρωσε πέρα από
 * αυτή την ευθυγράμμιση: η ανακούφιση μένει μονόδρομος ενός σκαλιού (avoid → caution — το
 * «πρόσεχε» παραμένει), και από 0,8 και πάνω το άθροισμα ξαναδικαιούται τη βαρύτερη λέξη.
 */
export const OVER_CAUTION_MAX_SHORE_WAVE_M = SEA_STATE_AMBER_M;

/**
 * Το άθροισμα δεν μπορεί να αρνηθεί μπάνιο ΚΑΤΩ από τόσα Μποφόρ. Είναι
 * `MEANINGFUL_WIND_TOP_PICK_BEAUFORT + 1` γραμμένο ως νούμερο, γιατί αυτό είναι όριο ΑΣΦΑΛΕΙΑΣ
 * και δεν πρέπει να κουνηθεί επειδή κάποιος συντόνισε το κατώφλι της κατάταξης.
 */
export const OVER_CAUTION_MAX_BEAUFORT = 4;

/**
 * Το ίδιο όριο όταν υπάρχει ΜΕΤΡΗΜΕΝΗ απόδειξη ότι όλο το νερό φεύγει από την ακτή. Ένα σκαλί
 * ψηλότερα, δηλαδή επιτρέπει τα 4 Μποφόρ και σταματάει στα 5 — εκεί όπου η ίδια η εφαρμογή
 * δίνει ήδη «Καλή» σε απόγειο επίπεδο νερό (utils/offshoreFlatWater), οπότε ένα «πρόσεχε» στα 4
 * δεν μπορεί να είναι πιο τολμηρό από ό,τι λέμε ήδη στα 5.
 */
export const OVER_CAUTION_DEPARTING_SEA_MAX_BEAUFORT = 5;

export interface OverCautionReliefInput {
  /** Τα μποφόρ του ζωντανού ανέμου, πριν από κάθε προσαύξηση κύματος. */
  beaufort: number;
  /**
   * Το νερό ΣΤΗΝ ΑΚΤΗ (`shoreWaveM`) όταν το ξέρουμε — αλλιώς η ανοιχτή θάλασσα. Ο καλών δίνει
   * το ίδιο νούμερο που διαβάζει ο κλάδος ακτής της ετυμηγορίας· δύο διαφορετικά νούμερα για
   * «το νερό εδώ» μέσα στην ίδια συνάρτηση είναι ακριβώς το σφάλμα που διορθώθηκε σήμερα.
   */
  seaAtShoreM: number;
  /**
   * Η περίοδος πίσω από το νερό (s), όταν την ξέρουμε. Το κατώφλι από πάνω συγκρίνεται σε
   * swell-equivalent ύψος (utils/waveCharacter.seaStateSeverityM) — το ΙΔΙΟ νόμισμα στο οποίο
   * το χρώμα συγκρίνει το δικό του SEA_STATE_AMBER_M — ώστε ένα κοντόκυμα 0,7 μ. @ 3 s
   * (severity 0,87, το χρώμα το λέει ήδη ΚΑΛΗ από θάλασσα) να ΜΗΝ παίρνει ανακούφιση, ενώ ένα
   * μακρύ 0,7 μ. @ 5 s (severity 0,70) να την παίρνει. Χωρίς περίοδο ο συντελεστής είναι 1 και
   * η σύγκριση πέφτει στο σκέτο ύψος, όπως παντού αλλού.
   */
  periodS?: number;
  /** Μετρημένη απόδειξη ότι κάθε συστατικό της θάλασσας ταξιδεύει ΜΑΚΡΙΑ από την ακτή. */
  departingSea?: boolean;
  /** Επίσημη προειδοποίηση αρχής — υπερισχύει τα πάντα και δεν ανακουφίζεται ποτέ. */
  officialWarning?: boolean;
  /** Αποθαλασσιά που έρχεται κατά πρόσωπο. */
  directSwell?: boolean;
  /** Ποινή κυματισμού μεγάλης περιόδου· >0 σημαίνει «σκάει βαρύτερα από το ύψος του». */
  swellSurgePenalty?: number;
}

/**
 * True όταν το ΑΘΡΟΙΣΜΑ δεν δικαιούται να πει «μην κολυμπήσεις». Δεν αποφασίζει την ετυμηγορία —
 * μόνο αφαιρεί τη βαρύτερη λέξη από το τραπέζι, αφήνοντας το «πρόσεχε».
 */
export const relievesOverCaution = ({
  beaufort,
  seaAtShoreM,
  periodS,
  departingSea,
  officialWarning,
  directSwell,
  swellSurgePenalty,
}: OverCautionReliefInput): boolean => {
  if (officialWarning) return false;
  if (directSwell) return false;
  if (typeof swellSurgePenalty === 'number' && swellSurgePenalty > 0) return false;
  if (!Number.isFinite(beaufort) || !Number.isFinite(seaAtShoreM)) return false;
  if ((seaStateSeverityM(seaAtShoreM, periodS) ?? seaAtShoreM) >= OVER_CAUTION_MAX_SHORE_WAVE_M) return false;
  const ceiling = departingSea ? OVER_CAUTION_DEPARTING_SEA_MAX_BEAUFORT : OVER_CAUTION_MAX_BEAUFORT;
  return beaufort < ceiling;
};
