/**
 * Κάτω από αυτό το στρώμα δεν ζητιέται καθόλου, και η ΔΙΕΥΘΥΝΣΗ δεν εφαρμόζεται.
 *
 * ΜΗΝ ΤΟ ΚΑΤΕΒΑΣΕΙΣ ΣΤΟ 2 «για πληρότητα». Στα 2 Μποφόρ δεν αλλάζει κανένα χρώμα από τη
 * διεύθυνση (0/54.142), αλλάζει μόνο το μοντελοποιημένο κύμα σε 4,8% των ωρών — και εκεί μιλάμε
 * για διαφορά της τάξης του ενός δέκατου του μέτρου σε νερό που όλες οι επιφάνειες ήδη λένε
 * ήρεμο. Το κόστος είναι πραγματικό (κάθε ώρα που περνάει την πύλη είναι ένα επιπλέον αίτημα
 * ανά κελί), το κέρδος όχι. (Η ΤΑΧΥΤΗΤΑ δεν έχει αυτή την πύλη — δες τον τίτλο.)
 */
export const OVER_WATER_MIN_BEAUFORT = 3;

const MS_TO_KMH = 3.6;

/** Μία ώρα του κελιού νερού μπροστά στην παραλία. */
export interface OverWaterWindHour {
  /** Διεύθυνση σε μοίρες, όπως τη δίνει το κελί νερού. */
  deg: number;
  /**
   * Ταχύτητα σε m/s, ΗΔΗ περασμένη από τη θαλάσσια πόρτα του `applyGustFloor` (υψόμετρο του
   * κελιού νερού → μόνο ο δάπεδος ασυνάρτητης ριπής). Προαιρετική: ώρα χωρίς τιμή κρατά τη
   * στεριανή ταχύτητα — ποτέ κενό, ποτέ μηδέν.
   */
  speed?: number;
}

/** `dt_txt` → άνεμος του κελιού νερού. Το χτίζει το `services/weatherService.fetchOverWaterWindBatch`. */
export type OverWaterWindByTime = Readonly<Record<string, OverWaterWindHour>>;

const beaufortOf = (wind: ForecastItem['wind'] | undefined): number => (
  wind && typeof wind.speed === 'number' && Number.isFinite(wind.speed)
    ? getBeaufortLevel(wind.speed * MS_TO_KMH)
    : 0
);

/**
 * Επιστρέφει το ίδιο αντικείμενο ανέμου όταν δεν αλλάζει τίποτα.
 *
 * Η ταυτότητα ΔΕΝ είναι μικροβελτιστοποίηση εδώ: το `applyBeachWindToDailyForecast` και το
 * `adjustDailyForecastToHour` κρίνουν με `===` (`ownWind !== item.wind`, `wind: hourItem.wind`),
 * και ολόκληρες οθόνες κάνουν memo πάνω σε αυτά. Ένα καινούριο αντικείμενο ανά ώρα θα ξαναέβαφε
 * τον χάρτη σε κάθε render χωρίς να έχει αλλάξει τίποτα.
 *
 * Η ΣΕΙΡΑ ΕΧΕΙ ΣΗΜΑΣΙΑ: πρώτα η ταχύτητα, μετά η διεύθυνση, γιατί η πύλη έντασης της
 * διεύθυνσης κρίνεται στο Μποφόρ που θα τυπωθεί — δηλαδή στο ΜΕΤΑ-swap.
 */
const withOverWaterWind = (wind: ForecastItem['wind'], sea: OverWaterWindHour): ForecastItem['wind'] => {
  let next = wind;

  if (typeof sea.speed === 'number' && Number.isFinite(sea.speed) && sea.speed !== wind.speed) {
    next = { ...next, speed: sea.speed, speedBeforeOverWater: wind.speed };
  }

  if (Number.isFinite(sea.deg) && beaufortOf(next) >= OVER_WATER_MIN_BEAUFORT) {
    const normalised = ((sea.deg % 360) + 360) % 360;
    if (normalised !== wind.deg) next = { ...next, deg: normalised, degBeforeOverWater: wind.deg };
  }

  return next;
};

/**
 * Βάζει τον άνεμο του νερού μέσα σε μια ημερήσια πρόγνωση παραλίας.
 *
 * ΠΟΤΕ ΝΑ ΚΛΗΘΕΙ: αμέσως μετά το `applyBeachWindToDailyForecast` και **ΠΡΙΝ** από το
 * `adjustDailyForecastToHour`. Ο λόγος είναι μηχανικός, όχι αισθητικός: η ημερήσια τιμή `wind`
 * ΔΕΝ είναι δικό της αντικείμενο — είναι ο άνεμος ενός ωριαίου στοιχείου, είτε του μεσημεριού
 * (`processForecastData`, `wind: midday.wind`) είτε της επιλεγμένης ώρας
 * (`adjustDailyForecastToHour`, `wind: hourItem.wind`). Αν διορθώσουμε πρώτα τις ώρες, η
 * ημερήσια τιμή έρχεται ήδη διορθωμένη από μόνη της. Αν το κάνουμε ανάποδα, η κάρτα και ο
 * χάρτης διαβάζουν διαφορετικό άνεμο για την ίδια στιγμή.
 *
 * Ο χάρτης ταυτότητας παρακάτω κλείνει την τρύπα για την περίπτωση που η ημερήσια τιμή δείχνει
 * σε ώρα που δεν άλλαξε: τότε μένει κι αυτή όπως ήταν, όπως πρέπει.
 */
export const applyOverWaterWind = (
  base: DailyForecast,
  windByTime: OverWaterWindByTime | undefined,
): DailyForecast => {
  if (!windByTime || !base?.hourly?.length) return base;

  // Κλειδί `unknown` επίτηδες: η ημερήσια τιμή `wind` έχει ΠΙΟ ΧΑΛΑΡΟ τύπο από τον ωριαίο
  // (το `gust` είναι προαιρετικό εκεί), αλλά είναι ΤΟ ΙΔΙΟ αντικείμενο με αναφορά. Ψάχνουμε
  // ταυτότητα, όχι σχήμα.
  const swapped = new Map<unknown, ForecastItem['wind']>();
  let changed = false;

  const hourly = base.hourly.map(item => {
    const wind = item?.wind;
    if (!wind) return item;
    const sea = windByTime[item.dt_txt];
    if (!sea) return item;

    const next = withOverWaterWind(wind, sea);
    if (next === wind) return item;
    swapped.set(wind, next);
    changed = true;
    return { ...item, wind: next };
  });

  if (!changed) return base;

  // Η ημερήσια τιμή είναι ο άνεμος ΜΙΑΣ ώρας, κρατημένος με αναφορά. Αν εκείνη η ώρα
  // άλλαξε, ακολουθεί· αν όχι, μένει όπως ήταν.
  const dayWind = (base.wind && swapped.get(base.wind)) || base.wind;
  return { ...base, wind: dayWind, hourly };
};

/**
 * Το ίδιο, για ολόκληρη τη σειρά ημερών μιας παραλίας. Επιστρέφει τον ΙΔΙΟ πίνακα όταν καμία
 * μέρα δεν άλλαξε, ώστε το `useMemo` παραπάνω να μη θεωρήσει ότι ήρθαν νέα δεδομένα.
 */
export const applyOverWaterWindToDays = (
  days: DailyForecast[],
  windByTime: OverWaterWindByTime | undefined,
): DailyForecast[] => {
  if (!windByTime || !days?.length) return days;
  let changed = false;
  const next = days.map(day => {
    const updated = applyOverWaterWind(day, windByTime);
    if (updated !== day) changed = true;
    return updated;
  });
  return changed ? next : days;
};

/**
 * ΑΞΙΖΕΙ ΝΑ ΠΛΗΡΩΣΟΥΜΕ ΤΙΣ ΚΛΗΣΕΙΣ ΓΙ' ΑΥΤΗ ΤΗΝ ΠΕΡΙΟΧΗ ΣΗΜΕΡΑ;
 *
 * Το στρώμα κοστίζει ένα πλήρες επιπλέον αίτημα ανά κελί νερού. Αν καμία ώρα του ορίζοντα δεν
 * φτάνει τα `OVER_WATER_MIN_BEAUFORT`, η διεύθυνση δεν θα εφαρμοζόταν σε καμία ώρα. Μετρημένο
 * εθνικά (§Γ37): στα ≤2 Μποφόρ ΚΑΝΕΝΑ χρώμα δεν αλλάζει από τη διεύθυνση σε 54.142 ώρες. Η
 * πύλη γλιτώνει ~30% των ωρών.
 *
 * ΑΠΟ 25/08 Η ΦΡΑΓΗ ΕΧΕΙ ΤΙΜΗΜΑ: η ΤΑΧΥΤΗΤΑ κερδίζει περισσότερο ακριβώς στην ψεύτικη ηρεμία
 * (§Γ52), και μια περιοχή που ολόκληρη μένει ≤2 Μποφόρ για έξι μέρες δεν θα τη δει. Κρατήθηκε
 * με απόφαση (Μίλτος 25/08) — το κόστος είναι κλήσεις, το κέρδος ένα σκαλί σε ώρες που όλες οι
 * επιφάνειες ήδη λένε «ήρεμα». Το `scripts/measureSeaSpeedRollout.mjs` μετράει πόσες ώρες
 * κρύβει (`hoursBehindFetchVeto`)· αν ο αριθμός αποδειχθεί μεγάλος, αυτή η συνάρτηση είναι το
 * μόνο πράγμα που αλλάζει.
 *
 * Διαβάζει τον άνεμο του ΣΤΕΡΙΑΝΟΥ κελιού, που είναι ο μόνος που έχουμε όταν αποφασίζουμε.
 */
export const anyHourReachesOverWaterMinimum = (items: Array<{ wind?: { speed?: number } }> | undefined): boolean => (
  !!items?.some(item => {
    const speed = item?.wind?.speed;
    return typeof speed === 'number' && Number.isFinite(speed)
      && getBeaufortLevel(speed * MS_TO_KMH) >= OVER_WATER_MIN_BEAUFORT;
  })
);

/**
 * Πόσες ώρες αυτής της πρόγνωσης διαβάζουν πια τη ΔΙΕΥΘΥΝΣΗ από τη θάλασσα. Το χρησιμοποιεί η
 * πύλη ποιότητας (`scripts/validateOverWaterWindLayer.mjs`) και το διαγνωστικό — καμία
 * επιφάνεια χρήστη.
 */
export const countOverWaterHours = (forecast: DailyForecast | undefined): number => (
  forecast?.hourly?.reduce(
    (n, item) => n + (typeof item?.wind?.degBeforeOverWater === 'number' ? 1 : 0),
    0,
  ) ?? 0
);

/** Το ίδιο για την ΤΑΧΥΤΗΤΑ: πόσες ώρες τυπώνουν το νούμερο του νερού. */
export const countOverWaterSpeedHours = (forecast: DailyForecast | undefined): number => (
  forecast?.hourly?.reduce(
    (n, item) => n + (typeof item?.wind?.speedBeforeOverWater === 'number' ? 1 : 0),
    0,
  ) ?? 0
);
