/** Κάτω από αυτό, το νερό λέγεται κρύο. */
export const WATER_COLD_BELOW_C = 21;

/** Έως και αυτό (και πάνω από το κρύο), το νερό λέγεται μέτριο. Πάνω από αυτό, ιδανικό. */
export const WATER_MILD_MAX_C = 24;

export type WaterTemperatureTier = 'cold' | 'mild' | 'ideal';

/** Ο τόνος που ήδη μιλάει η σελίδα παραλίας. Δεν είναι χρώμα πινέζας και δεν το αγγίζει. */
export type WaterTemperatureTone = 'rough' | 'moderate' | 'calm';

const DESCRIPTOR: Record<WaterTemperatureTier, Record<LanguageCode, string>> = {
  cold: { en: 'cold', gr: 'κρύο', de: 'kalt', it: 'fredda', fr: 'froide' },
  mild: { en: 'mild', gr: 'μέτριο', de: 'mild', it: 'tiepida', fr: 'tempérée' },
  ideal: { en: 'ideal', gr: 'ιδανικό', de: 'ideal', it: 'ideale', fr: 'idéale' },
};

const TONE: Record<WaterTemperatureTier, WaterTemperatureTone> = {
  cold: 'rough',
  mild: 'moderate',
  ideal: 'calm',
};

export const waterTemperatureTier = (celsius: number): WaterTemperatureTier => {
  if (celsius < WATER_COLD_BELOW_C) return 'cold';
  if (celsius <= WATER_MILD_MAX_C) return 'mild';
  return 'ideal';
};

export interface WaterTemperatureReading {
  celsius: number;
  tier: WaterTemperatureTier;
  descriptor: string;
  tone: WaterTemperatureTone;
}

/**
 * Η μία απάντηση για «πώς είναι το νερό». Επιστρέφει `undefined` όταν δεν υπάρχει αριθμός —
 * ΠΟΤΕ δεν μαντεύει και ποτέ δεν πέφτει σε «κρύο»: άγνωστη θερμοκρασία σημαίνει σιωπή, όχι
 * προειδοποίηση. (Η ίδια αρχή με το `unverified` της 10/08: αν δεν ξέρουμε, δεν μιλάμε.)
 */
export const resolveWaterTemperature = (
  celsius: number | undefined,
  language: LanguageCode,
): WaterTemperatureReading | undefined => {
  if (typeof celsius !== 'number' || !Number.isFinite(celsius)) return undefined;
  const tier = waterTemperatureTier(celsius);
  return {
    celsius,
    tier,
    descriptor: DESCRIPTOR[tier][language],
    tone: TONE[tier],
  };
};

const WATER_LABEL: Record<LanguageCode, string> = {
  en: 'Water', gr: 'Νερό', de: 'Wasser', it: 'Acqua', fr: 'Eau',
};

/**
 * Η γραμμή της ΚΑΡΤΑΣ — και σωπαίνει όταν το νερό είναι ιδανικό.
 *
 * ΓΙΑΤΙ ΟΧΙ ΠΑΝΤΑ. Τον Αύγουστο σχεδόν κάθε ελληνική παραλία είναι στους 24-26 °C, δηλαδή
 * «ιδανικό». Μια γραμμή που λέει το ίδιο πράγμα σε κάθε κάρτα κάθε μέρα δεν είναι πληροφορία,
 * είναι θόρυβος — και κοστίζει ύψος σε οθόνη 320 px όπου ήδη παλεύουν δύο νούμερα. Είναι η ίδια
 * απόφαση σιωπής με το `choppySeaCopy` (43,6% → 6,9%), με τη γραμμή αιτίας του §Γ14 που σωπαίνει
 * στις μπλε, και με το φίλτρο του §Γ16 που κρύβεται όταν υπάρχουν ιδανικές.
 *
 * Μιλάει δηλαδή ΑΚΡΙΒΩΣ όταν αλλάζει απόφαση: κρύο νερό της άνοιξης/του φθινοπώρου, και οι
 * μέρες μετά από μελτέμι όπου η ανάβλυση ρίχνει τις βόρειες ακτές 4-6 βαθμούς.
 *
 * ΔΕΝ ΕΙΝΑΙ ΤΑΜΠΕΛΑ ΚΑΙ ΔΕΝ ΕΙΝΑΙ ΕΤΥΜΗΓΟΡΙΑ: δεν περιέχει «κατάλληλη», «απόφυγε» ή οτιδήποτε
 * κρίνει την παραλία — περιγράφει έναν αριθμό. Το «~» μένει γιατί η τιμή είναι μοντέλο, όχι
 * μέτρηση στην ακτή.
 */
export const buildWaterTemperatureCardLine = (
  celsius: number | undefined,
  language: LanguageCode,
): string | undefined => {
  const reading = resolveWaterTemperature(celsius, language);
  if (!reading || reading.tier === 'ideal') return undefined;
  return `${WATER_LABEL[language]} ~${Math.round(reading.celsius)}° · ${reading.descriptor}`;
};
